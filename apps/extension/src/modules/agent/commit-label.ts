/** Accents and case off; "ß" is "ss". Hangul and kana survive the round trip. */
function fold(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .normalize("NFC")
    .replace(/ß/g, "ss")
    .toLowerCase();
}

// Han, kana and Hangul run words together ("決済する", "결제하기"), so a term
// there matches inside a word. Every other script gets word edges, which is
// what keeps "post" from firing on "postal code" and "pay" on "payment history".
const SPACELESS = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}]/u;

const escape = (term: string) => term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const alternation = (terms: string[]) => terms.map((t) => escape(fold(t))).join("|");

const all = [...new Set(Object.values(TERMS).flat())];
const spaced = new RegExp(
  `(?<![\\p{L}\\p{N}])(?:${alternation(all.filter((t) => !SPACELESS.test(t)))})(?![\\p{L}\\p{N}])`,
  "u",
);
const spaceless = new RegExp(alternation(all.filter((t) => SPACELESS.test(t))), "u");

/** Whether a control's visible name reads as an act that commits the user. */
export function labelCommits(label: string): boolean {
  const text = fold(label);
  return spaced.test(text) || spaceless.test(text);
}
